#include <stdio.h>

/* 程序51：学习使用按位与 &。
   同为1才为1。经典用途：判断奇偶（x & 1）、清零特定位 */

int main(void)
{
    int a = 12;      /* 1100 */
    int b = 10;      /* 1010 */

    printf("a = %d (1100), b = %d (1010)\n", a, b);
    printf("a & b = %d (1000)\n", a & b);

    /* 用途1：判断奇偶 */
    printf("12 & 1 = %d (偶数)\n", 12 & 1);
    printf("13 & 1 = %d (奇数)\n", 13 & 1);

    /* 用途2：清零低 2 位 */
    printf("12 & ~3 = %d (1100 & 1100)\n", 12 & ~3);
    return 0;
}
