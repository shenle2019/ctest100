#include <stdio.h>

/* 程序21：猴子吃桃。猴子第一天摘下若干个桃子，当即吃了一半，还不过瘾，
   又多吃了一个。以后每天早上都吃了前一天剩下的一半零一个。
   到第10天早上想再吃时，见只剩下一个桃子了。求第一天共摘了多少。 */

int main(void)
{
    int day = 9;
    int peach = 1;   /* 第10天早上剩 1 个 */

    /* 逆向递推：第 n 天早上剩 x 个，则第 n-1 天早上剩 (x+1)*2 个 */
    while (day > 0) {
        peach = (peach + 1) * 2;
        day--;
    }

    printf("第一天共摘了 %d 个桃子\n", peach);
    return 0;
}
