#include <stdio.h>

/* 程序81：809*??=800*??+9*??+1，其中 ?? 代表的两位数，
   8*?? 的结果为两位数，9*?? 的结果为 3 位数。
   求 ?? 代表的两位数，及 809*?? 后的结果。
   分析：穷举两位数 10~99，同时满足三个条件 */

int main(void)
{
    int n;
    int found = 0;

    for (n = 10; n <= 99; n++) {
        if (8 * n >= 10 && 8 * n < 100 &&      /* 8*?? 两位数 */
            9 * n >= 100 && 9 * n < 1000 &&    /* 9*?? 三位数 */
            809 * n == 800 * n + 9 * n + 1) {  /* 等式成立 */
            found = 1;
            printf("?? = %d\n", n);
            printf("809 * %d = %d\n", n, 809 * n);
            printf("800 * %d + 9 * %d + 1 = %d\n", n, n, 800 * n + 9 * n + 1);
        }
    }

    /* 809n = 800n + 9n 恒成立，等式右边加 1 后永不等，此题无解 */
    if (!found) {
        printf("无解：809n 恒等于 800n + 9n，右边 +1 后等式永不成立\n");
    }
    return 0;
}
