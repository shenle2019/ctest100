#include <stdio.h>

/* 程序52：学习使用按位或 |。
   有1即为1。经典用途：把特定位设为1 */

int main(void)
{
    int a = 12;      /* 1100 */
    int b = 10;      /* 1010 */

    printf("a = %d (1100), b = %d (1010)\n", a, b);
    printf("a | b = %d (1110)\n", a | b);

    /* 用途：把第 0 位设为 1（最低位从 0 还是 1 都变成 1） */
    printf("12 | 1 = %d (1100 | 0001 = 1101)\n", 12 | 1);
    printf("13 | 1 = %d (1101 | 0001 = 1101)\n", 13 | 1);
    return 0;
}
