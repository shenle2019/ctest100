#include <stdio.h>

/* 程序89：数据加密。
   某个公司采用公用电话传递数据，数据是四位的整数，在传递过程中是加密的，
   加密规则如下：每位数字都加上5，然后用和除以10的余数代替该数字，
   再将第一位和第四位交换，第二位和第三位交换 */

int main(void)
{
    int n, d[4], i, tmp;

    printf("请输入一个四位整数: ");
    scanf("%d", &n);

    /* 拆出四位数字 */
    d[0] = n / 1000 % 10;
    d[1] = n / 100 % 10;
    d[2] = n / 10 % 10;
    d[3] = n % 10;

    /* 每位加5取余10 */
    for (i = 0; i < 4; i++) {
        d[i] = (d[i] + 5) % 10;
    }

    /* 第一位和第四位交换，第二位和第三位交换 */
    tmp = d[0]; d[0] = d[3]; d[3] = tmp;
    tmp = d[1]; d[1] = d[2]; d[2] = tmp;

    printf("加密后的数字: %d%d%d%d\n", d[0], d[1], d[2], d[3]);
    return 0;
}
