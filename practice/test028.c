#include <stdio.h>

/* 程序28：有五个人坐在一起，问第五个人多少岁？他说比第4个人大2岁。
   问第4个人岁数，他说比第3个人大2岁。问第三个人，又说比第2人大2岁。
   问第2个人，说比第一个人大2岁。最后问第一个人，他说是10岁。
   请问第五个人多大？
   递归公式：age(n) = age(n-1) + 2，结束条件 age(1) = 10 */

int age(int n)
{
    if (n == 1) {
        return 10;            /* 第一个人的年龄是结束条件 */
    }
    return age(n - 1) + 2;    /* 每个人都比前一个大2岁 */
}

int main(void)
{
    printf("第五个人 %d 岁\n", age(5));
    return 0;
}
