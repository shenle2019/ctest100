#include <stdio.h>

/* 程序24：有一分数序列：2/1，3/2，5/3，8/5，13/8，21/13...
   求出这个数列的前20项之和。
   分析：分子分母都是斐波那契数列，后一项的分子=前一项分子+分母 */

int main(void)
{
    double a = 2.0, b = 1.0;   /* a 分子，b 分母 */
    double sum = 0.0, t;
    int i;

    for (i = 1; i <= 20; i++) {
        sum += a / b;
        t = a;          /* 暂存分子 */
        a = a + b;      /* 新分子 = 旧分子 + 旧分母 */
        b = t;          /* 新分母 = 旧分子 */
    }

    printf("前20项之和为 %.6f\n", sum);
    return 0;
}
